# Також вивести загальну суму.

age = int(input("Введіть вік першої людини: "))
age2 = int(input("Введіть вік другої людини: "))
age3 = int(input("Введіть вік третьої людини: "))

if age <= 12:
    ticket_price1 = 80
elif age <= 65:
    ticket_price1 = 200
else:
    ticket_price1 = 120

if age2 <= 12:
    ticket_price2 = 80
elif age2 <= 65:
    ticket_price2 = 200
else:
    ticket_price2 = 120

if age3 <= 12:
    ticket_price3 = 80
elif age3 <= 65:
    ticket_price3 = 200
else:
    ticket_price3 = 120

total = ticket_price1 + ticket_price2 + ticket_price3

print(f"Вартість квитка за першу людину: {ticket_price1} грн")
print(f"Вартість квитка за другу людину: {ticket_price2} грн")
print(f"Вартість квитка за третю людину: {ticket_price3} грн")
print(f"Загальна сума: {total} грн")
print("Гарного дня!")
