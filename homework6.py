# Користувач вводить розмір футболки(S, M, L або XL).
# Якщо введено S або M – спитайте колір футболки(немає
# фіолетових і жовтих)
# Якщо введено L – повідомте що всі футболки цього
# розміру закінчились
# Якщо введено XL – спитайте тип тканини(є лише
# бавовна)
# В результаті програма повинна вивести «Є в наявності»
# або «Немає в наявності

size = input("Введіть розмір футболки(S, M, L або XL: ")

if size == "S" or size == "M":
    color = input(print("Оберіть колір футболки: "))
    if color == "фіолетовий" or size == "жовтий":
        print("Немає в наявності")
    else:
        print("Є в наявності")
elif size == "L":
    print("Всі футболки цього розміру закінчились")
elif size == "XL":
    fabric = input("Оберіть тип тканини: ")
    if fabric == "бавовна":
        print("Є в наявності")
    else:
        print("Немає в наявності")
else:
    print("Неправильний розмір")


