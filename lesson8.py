# Завдання 6
# Напишіть програму для введення пароля від банкомату.
# У користувача є лише три спроби
# В кінці виведіть чи вдалось правильно ввести пароль

password = "lalala"
attempts = 3

while True:
    user_password = input("Введіть пароль: ")

    attempts -= 1

    if user_password == password:
        print("Правильний пароль")
        break

    if attempts == 0:
        print("Спроби закінчились")
        break

    else:
        print("Пароль не правильний")
