# Завдання 6
# Користувач вводить суму кредиту та термін у роках.
# Виберіть відсоткову ставку за такими умовами:
# ● Для кредиту до 10 000$ на термін до 3 років – ставка
# 8%
# ● Для кредиту до 10 000$ на термін понад 3 роки –
# ставка 10%
# ● Для кредиту від 10 001$ до 50 000$ на термін до 3
# років – ставка 12%
# ● Для кредиту від 10 001$ до 50 000$ на термін понад 3
# роки – ставка 14%
# ● Для кредиту від 50 000$ на будь-який термін – ставка
# 20%
# Виведіть відсоткову ставку, загальну суму кредиту та
# щомісячний платіж
# Загальна сума кредиту вираховується так

sum_credit = float(input("Введіть суму кредиту: "))
period = float(input("Введіть термін у роках: "))

if sum_credit <= 10000 and period <= 3:
    rate = 8
elif sum_credit <= 10000 and period > 3:
    rate = 10
elif sum_credit >= 10001 and sum_credit <= 50000 and period <= 3:
    rate = 12
elif sum_credit >= 10001 and sum_credit <= 50000 and period > 3:
    rate = 14
else:
    rate = 20

total = sum_credit * (1 + rate / 100) ** period
monthly = total / (period * 12)

print(f"Відсоткова ставка: {rate}%")
print(f"Загальна сума кредиту: {total:.0f}")
print(f"Щомісячний платіж: {monthly:.0f}")
