# Завдання 6
# Щоб спекти пиріг потрібно 4 яблука та 1.2 літра молока.
# Користувач вводить кількість яблук та молока(у літрах).
# Виведіть скільки він може спекти пирогів.
# Виведіть скільки яблук та молока залишиться.
# Приклад:
# Введіть кількість яблук: 5
# Введіть кількість молока (л): 10
# Можна спекти пирогів: 1
# Залишиться яблук: 1
# Залишиться молока: 8.8

apples = int(input("Введіть кількість яблук: "))
milk = float(input("Введіть кількість молока (л): "))
pie_apple = apples // 4
pie_milk = milk // 1.2
pies = min(pie_apple, pie_milk)
print(f"Ви можете спекти: {pies:.0f}")
remaining_apple = apples - (pies * 4)
remaining_milk = milk - (pies * 1.2)
print(f"Залишиться яблук: {remaining_apple:.0f}")
print(f"Залишиться молока: {remaining_milk:.2f}")
